"""Convert TTF fonts to 4-bit anti-aliased, fixed-cell bitmap fonts for the M01.

usage: python -I tools/mkfont.py  (run from m01fw/) -> writes src/fonts.c / src/fonts.h
Fonts: JetBrains Mono (SIL OFL 1.1, lib/fonts/OFL.txt).
"""
from PIL import Image, ImageDraw, ImageFont

ASCII = "".join(chr(c) for c in range(32, 127))
SPECS = [
    # name,      ttf,                       px, chars
    ("font_big", "JetBrainsMono-Bold.ttf",     56, "0123456789.- "),
    ("font_med", "JetBrainsMono-SemiBold.ttf", 22, ASCII + "\u00b0"),
    ("font_sml", "JetBrainsMono-Medium.ttf",   14, ASCII + "\u00b0"),
]


def build(name, ttf, px, chars):
    f = ImageFont.truetype(f"lib/fonts/{ttf}", px)
    adv = round(f.getlength("0"))
    asc, desc = f.getmetrics()
    tall = asc + desc
    imgs = []
    for ch in chars:
        im = Image.new("L", (adv, tall), 0)
        ImageDraw.Draw(im).text((0, 0), ch, font=f, fill=255)
        imgs.append(im)
    # trim rows unused by every glyph (keeps cells compact)
    top = min((im.getbbox() or (0, tall, 0, tall))[1] for im in imgs)
    bot = max((im.getbbox() or (0, 0, 0, 0))[3] for im in imgs)
    h = bot - top
    data = bytearray()
    for im in imgs:
        px_ = im.crop((0, top, adv, bot)).load()
        nib = [px_[x, y] >> 4 for y in range(h) for x in range(adv)]
        if len(nib) % 2: nib.append(0)
        data += bytes((nib[i] << 4) | nib[i + 1] for i in range(0, len(nib), 2))
    glyph_bytes = (adv * h + 1) // 2
    codes = [ord(c) if ord(c) < 128 else 0x7F for c in chars]   # degree sign -> 0x7F
    return name, adv, h, top, glyph_bytes, codes, data


out_c = ['/* Generated by tools/mkfont.py from JetBrains Mono (SIL OFL 1.1). Do not edit. */',
         '#include "fonts.h"', '']
out_h = ['/* Generated by tools/mkfont.py. Do not edit. */', '#pragma once', '#include "gfx.h"', '']
for spec in SPECS:
    name, w, h, top, gb, codes, data = build(*spec)
    m = [0xFF] * 128
    for i, c in enumerate(codes): m[c] = i
    out_c.append(f"static const uint8_t {name}_bits[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        out_c.append("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    out_c.append("};")
    out_c.append(f"static const uint8_t {name}_map[128] = {{" + ",".join(str(v) for v in m) + "};")
    out_c.append(f"const font_t {name} = {{ {w}, {h}, {gb}, {name}_map, {name}_bits }};")
    out_c.append("")
    out_h.append(f"extern const font_t {name};   /* {w}x{h} cells, {len(codes)} glyphs, {len(data)} bytes */")
    print(f"{name}: {w}x{h}, {len(codes)} glyphs, {len(data)} bytes")
out_h.append("#define DEG \"\\x7f\"   /* degree sign in font_med / font_sml */")
open("src/fonts.c", "w", newline="\n").write("\n".join(out_c) + "\n")
open("src/fonts.h", "w", newline="\n").write("\n".join(out_h) + "\n")
